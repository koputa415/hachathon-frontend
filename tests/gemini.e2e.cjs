const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { randomBytes } = require('node:crypto')
const { chromium } = require('playwright')
const base = process.env.GEMINI_E2E_BASE_URL || 'http://localhost:5182'
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname) || process.env.GEMINI_E2E_ALLOW_WRITES !== '1') throw new Error('Disposable local DB only')
const output = process.env.GEMINI_E2E_OUTPUT_DIR || path.resolve('test-results/gemini')
const suffix = randomBytes(6).toString('hex'), password = randomBytes(24).toString('base64url')
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAMAAAACCAIAAAASFvFNAAAAFUlEQVR4nGPUCKhgYGBgYGBgYoABABDMAPTRO+Z7AAAAAElFTkSuQmCC', 'base64')
async function run() {
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || undefined })
  const context = await browser.newContext({ viewport: { width: 1280, height: 1000 } })
  const page = await context.newPage(); page.setDefaultTimeout(15000)
  const checks = [], errors = []
  page.on('pageerror', error => errors.push(error.message))
  const draft = page.getByRole('region', { name: 'AIで商品説明を下書き', exact: true })
  const description = page.getByLabel('商品の説明', { exact: true })
  async function fields(title) {
    await page.getByLabel('商品名', { exact: true }).fill(title)
    await page.getByLabel('カテゴリ（趣味）', { exact: true }).selectOption('その他')
    await page.getByLabel('商品の状態', { exact: true }).selectOption('目立った傷や汚れなし')
    await page.getByLabel('価格（円）', { exact: true }).fill('7777')
    await page.getByLabel('商品画像', { exact: true }).setInputFiles({ name: 'item.png', mimeType: 'image/png', buffer: png })
  }
  try {
    await page.goto(`${base}/#/listing`)
    await page.getByRole('button', { name: '新規登録に切り替える', exact: true }).click()
    await page.getByLabel('表示名', { exact: true }).fill('Gemini確認')
    await page.getByLabel('メールアドレス', { exact: true }).fill(`gemini-${suffix}@example.com`)
    await page.getByLabel('パスワード（8〜128文字）', { exact: true }).fill(password)
    await page.getByRole('button', { name: '登録して続ける', exact: true }).click()
    await page.getByRole('heading', { name: '道具を出品する', exact: true }).waitFor()
    assert.equal(await draft.getByRole('button', { name: '説明文の下書きを生成', exact: true }).isDisabled(), true)
    await fields(`道具-${suffix}`)
    await description.fill('自分で書いた説明を保持します。')
    await draft.getByRole('button', { name: '説明文の下書きを生成', exact: true }).click()
    await draft.getByLabel('AIが生成した説明文の下書き', { exact: true }).waitFor()
    assert.equal(await description.inputValue(), '自分で書いた説明を保持します。')
    await draft.getByRole('button', { name: 'この下書きを説明欄に反映', exact: true }).click()
    assert.match(await description.inputValue(), /写真と商品情報/)
    const edited = (await description.inputValue()) + ' 出品者が状態を確認して編集しました。'
    await description.fill(edited)
    await page.screenshot({ path: path.join(output, 'description-draft.png'), fullPage: true })
    const response = page.waitForResponse(r => r.url().endsWith('/api/items/with-image') && r.status() === 201)
    await page.locator('form').getByRole('button', { name: '出品する', exact: true }).click()
    const created = await (await response).json()
    await page.getByRole('heading', { name: '出品が完了しました', exact: true }).waitFor()
    assert.equal(created.description, edited)
    assert.equal(created.category, 'その他')
    assert.equal(created.price, 7777)
    checks.push('写真と入力からAI下書きを生成し、手入力を保持。反映後の編集文をその他の商品として実DBへ保存')
    await page.getByRole('button', { name: '続けて出品する', exact: true }).click()
    await fields(`生成失敗-${suffix}`)
    await description.fill('生成に失敗しても手入力で出品します。')
    await draft.getByRole('button', { name: '説明文の下書きを生成', exact: true }).click()
    await draft.getByText('現在、AIの下書きを生成できません。説明文を手入力して出品できます。', { exact: true }).waitFor()
    const failedResponse = page.waitForResponse(r => r.url().endsWith('/api/items/with-image') && r.status() === 201)
    await page.locator('form').getByRole('button', { name: '出品する', exact: true }).click()
    assert.equal((await (await failedResponse).json()).description, '生成に失敗しても手入力で出品します。')
    await page.getByRole('heading', { name: '出品が完了しました', exact: true }).waitFor()
    checks.push('生成失敗を表示し、写真・手入力説明・価格を保持して通常出品できる')
    await page.getByRole('button', { name: '続けて出品する', exact: true }).click()
    await fields(`待機-${suffix}`)
    await draft.getByRole('button', { name: '説明文の下書きを生成', exact: true }).click()
    await page.getByLabel('商品名', { exact: true }).fill('別の商品へ変更')
    await page.waitForTimeout(1300)
    assert.equal(await draft.getByLabel('AIが生成した説明文の下書き', { exact: true }).count(), 0)
    await page.getByRole('button', { name: '入力をクリア', exact: true }).click()
    assert.equal(await description.inputValue(), '')
    assert.equal(await draft.getByRole('button', { name: '説明文の下書きを生成', exact: true }).isDisabled(), true)
    checks.push('入力変更後の古い下書きを破棄し、クリアで画像・文章・生成表示を初期化')
    let introRequests = 0
    page.on('request', request => { if (request.url().includes('/hobby-introduction')) introRequests += 1 })
    await page.goto(`${base}/#/items/${created.id}`)
    await page.getByRole('heading', { name: created.title, exact: true }).waitFor()
    assert.equal(await page.getByRole('heading', { name: /って？ 最初の一歩/ }).count(), 0)
    assert.equal(introRequests, 0)
    checks.push('その他の商品では趣味紹介カードを表示せず、生成APIも呼び出さない')
    const token = await page.evaluate(() => JSON.parse(sessionStorage.getItem('hackathon.auth.session')).token)
    async function coreItem(category) {
      const response = await context.request.post(`${base}/api/items`, { headers: { Authorization: `Bearer ${token}` }, data: {
        title: `${category}の体験用-${suffix}`, category, description: '趣味紹介の表示確認です。', condition: '未使用に近い', price: 1234,
      } })
      assert.equal(response.status(), 201)
      return response.json()
    }
    const music = await coreItem('楽器'), camera = await coreItem('カメラ')
    await page.goto(`${base}/#/items/${music.id}`)
    const musicCard = page.getByRole('region', { name: '楽器って？ 最初の一歩', exact: true })
    await musicCard.getByText('AIが生成した趣味の紹介です。', { exact: true }).waitFor()
    await page.screenshot({ path: path.join(output, 'hobby-introduction.png'), fullPage: true })
    await page.goto(`${base}/#/items/${camera.id}`)
    const cameraCard = page.getByRole('region', { name: 'カメラって？ 最初の一歩', exact: true })
    await cameraCard.getByText('基本のヒント', { exact: true }).waitFor()
    assert.equal(await cameraCard.getByText('AIが生成した趣味の紹介です。', { exact: true }).count(), 0)
    checks.push('5趣味の詳細にAI生成を明示した紹介を表示し、生成失敗時は基本情報へ切り替える')
    await page.route('**/api/items/*/hobby-introduction', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{}' }))
    await page.goto(`${base}/#/items/${music.id}`)
    await musicCard.getByText('紹介を取得できませんでした。', { exact: false }).waitFor()
    await page.getByText('趣味紹介の表示確認です。', { exact: true }).waitFor()
    await page.unroute('**/api/items/*/hobby-introduction')
    await musicCard.getByRole('button', { name: '紹介を再取得', exact: true }).click()
    await musicCard.getByText('AIが生成した趣味の紹介です。', { exact: true }).waitFor()
    checks.push('紹介APIの通信失敗でも商品詳細を保持し、代替表示から再取得できる')
    const sellerResponse = await context.request.post(`${base}/api/auth/register`, { data: {
      email: `gemini-seller-${suffix}@example.com`, display_name: '再出品元の出品者', password,
    } })
    assert.equal(sellerResponse.status(), 201)
    const seller = await sellerResponse.json()
    async function purchased(category, title, withImage = true) {
      const fields = { title: `${title}-${suffix}`, category, description: '以前の説明です。現在の状態は購入者が確認します。', condition: '目立った傷や汚れなし', price: 2500 }
      const response = withImage
        ? await context.request.post(`${base}/api/items/with-image`, { headers: { Authorization: `Bearer ${seller.access_token}` }, multipart: {
          item: JSON.stringify(fields), image: { name: 'source.png', mimeType: 'image/png', buffer: png },
        } })
        : await context.request.post(`${base}/api/items`, { headers: { Authorization: `Bearer ${seller.access_token}` }, data: fields })
      assert.equal(response.status(), 201)
      const item = await response.json()
      const result = await context.request.post(`${base}/api/purchases`, { headers: { Authorization: `Bearer ${token}` }, data: { item_id: item.id } })
      assert.equal(result.status(), 201)
      return { purchase: await result.json(), item }
    }
    const source = await purchased('その他', '再出品する道具')
    let preparations = 0
    page.on('request', request => { if (request.url().endsWith(`/items/relisting-draft/${source.purchase.id}`)) preparations += 1 })
    await page.goto(`${base}/#/purchases`)
    await page.getByRole('region', { name: `購入番号 ${source.purchase.id}`, exact: true }).getByRole('link', { name: 'この道具を再出品する', exact: true }).click()
    await page.getByRole('heading', { name: '購入した道具を再出品する', exact: true }).waitFor()
    assert.match(await description.inputValue(), /再出品のための新しい下書き/)
    assert.equal(await page.getByLabel('商品名', { exact: true }).inputValue(), source.item.title)
    assert.equal(await page.getByLabel('カテゴリ（趣味）', { exact: true }).inputValue(), 'その他')
    assert.equal(await page.getByLabel('商品の状態', { exact: true }).inputValue(), '')
    assert.equal(await page.getByLabel('価格（円）', { exact: true }).inputValue(), '')
    await page.getByAltText('選択した商品画像のプレビュー', { exact: true }).waitFor()
    assert.equal(preparations, 1)
    await page.getByLabel('商品の状態', { exact: true }).selectOption('やや傷や汚れあり')
    await page.getByLabel('価格（円）', { exact: true }).fill('3456')
    await draft.getByRole('button', { name: '説明文の下書きを生成', exact: true }).click()
    await draft.getByLabel('AIが生成した説明文の下書き', { exact: true }).waitFor()
    assert.match(await draft.getByLabel('AIが生成した説明文の下書き', { exact: true }).inputValue(), /再出品/)
    await draft.getByRole('button', { name: 'この下書きを説明欄に反映', exact: true }).click()
    const relistedText = (await description.inputValue()) + ' 現在の小さな傷を確認して追記しました。'
    await description.fill(relistedText)
    await page.getByRole('region', { name: 'AIによる表示価格の予測', exact: true }).locator('strong').waitFor()
    await page.screenshot({ path: path.join(output, 'relisting-edit.png'), fullPage: true })
    const newResponse = page.waitForResponse(response => response.url().endsWith('/api/items/with-image') && response.status() === 201)
    await page.locator('form').getByRole('button', { name: '出品する', exact: true }).click()
    const relisted = await (await newResponse).json()
    await page.getByRole('heading', { name: '出品が完了しました', exact: true }).waitFor()
    assert.notEqual(relisted.id, source.item.id)
    assert.equal(relisted.category, 'その他')
    assert.equal(relisted.price, 3456)
    assert.equal(relisted.description, relistedText)
    assert.notEqual(relisted.seller_id, seller.user.id)
    const oldItem = await (await context.request.get(`${base}/api/items/${source.item.id}`)).json()
    assert.equal(oldItem.status, 'sold')
    assert.equal(oldItem.description, source.item.description)
    assert.equal(oldItem.price, 2500)
    assert.equal((await context.request.get(`${base}/api/items/${relisted.id}/image`)).status(), 200)
    checks.push('履歴から1回の操作でその他の再出品下書きを自動生成。写真を引き継ぎ、現状・価格・生成文を編集して別商品として保存し、元の売却済み商品を保持')
    await page.getByRole('button', { name: '続けて出品する', exact: true }).click()
    await page.getByRole('heading', { name: '道具を出品する', exact: true }).waitFor()
    assert.equal(await page.getByLabel('商品名', { exact: true }).inputValue(), '')
    assert.equal(await description.inputValue(), '')
    checks.push('再出品後に続けて出品を選ぶと、元商品情報と再出品用の文脈を残さず空のフォームに戻る')
    const failedSource = await purchased('楽器', '生成失敗の再出品')
    await page.goto(`${base}/#/purchases/${failedSource.purchase.id}/relist`)
    await page.getByRole('heading', { name: '購入した道具を再出品する', exact: true }).waitFor()
    await page.getByText('AIの再生成ができなかったため、以前の説明を表示しています。', { exact: false }).waitFor()
    assert.equal(await description.inputValue(), failedSource.item.description)
    await description.fill('AI生成なしで、現在の状態を自分で記載して再出品します。')
    await page.getByLabel('商品の状態', { exact: true }).selectOption('未使用に近い')
    await page.getByLabel('価格（円）', { exact: true }).fill('1234')
    const manualResponse = page.waitForResponse(response => response.url().endsWith('/api/items/with-image') && response.status() === 201)
    await page.locator('form').getByRole('button', { name: '出品する', exact: true }).click()
    assert.equal((await (await manualResponse).json()).description, 'AI生成なしで、現在の状態を自分で記載して再出品します。')
    await page.getByRole('heading', { name: '出品が完了しました', exact: true }).waitFor()
    checks.push('クラスタ内の再出品でも生成失敗を補助機能の失敗として扱い、以前の写真と手入力で出品できる')
    const missingPhoto = await purchased('その他', '写真なしの購入', false)
    await page.goto(`${base}/#/purchases/${missingPhoto.purchase.id}/relist`)
    await page.getByRole('heading', { name: '購入した道具を再出品する', exact: true }).waitFor()
    await page.getByText('以前の写真を引き継げませんでした。現在の写真を選んでください。', { exact: true }).waitFor()
    assert.equal(await page.getByLabel('商品画像', { exact: true }).evaluate(input => input.required), true)
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true)
    await page.screenshot({ path: path.join(output, 'mobile-relisting.png'), fullPage: true })
    await page.getByRole('button', { name: '入力をクリア', exact: true }).click()
    await page.getByRole('heading', { name: '道具を出品する', exact: true }).waitFor()
    assert.equal(await description.inputValue(), '')
    await page.getByRole('button', { name: 'ログアウト', exact: true }).click()
    await page.goto(`${base}/#/purchases/${missingPhoto.purchase.id}/relist`)
    await page.getByRole('heading', { name: 'ログイン', exact: true }).waitFor()
    await page.getByLabel('メールアドレス', { exact: true }).fill(`gemini-${suffix}@example.com`)
    await page.getByLabel('パスワード', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'ログインして続ける', exact: true }).click()
    await page.getByRole('heading', { name: '購入した道具を再出品する', exact: true }).waitFor()
    assert.equal(page.url(), `${base}/#/purchases/${missingPhoto.purchase.id}/relist`)
    checks.push('写真がない購入では手動の写真選択を必須にし、モバイル・ログイン復帰先も再出品に対応')
    await page.goto(`${base}/#/purchases/999999/relist`)
    await page.getByText('再出品できる購入記録が見つかりません。', { exact: true }).waitFor()
    assert.equal(await page.getByRole('heading', { name: '購入した道具を再出品する', exact: true }).count(), 0)
    checks.push('存在しない購入の直接URLは拒否し、元情報のない再出品フォームを表示しない')
    assert.deepEqual(errors, [])
    await fs.writeFile(path.join(output, 'verification.json'), JSON.stringify({ checks, passed: checks.length, runtimeErrors: errors, gemini: 'test-only upstream fixture; no real Gemini call' }, null, 2))
    console.log(JSON.stringify({ checks, passed: checks.length, runtimeErrors: errors }, null, 2))
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }).catch(() => {})
    throw error
  } finally { await browser.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
